        return {
            text = "你盯着信的最后几行。那个没写完的「代价」。\n\n"
                .. "你能猜到一些。打开封印，归还核心。代价——\n"
                .. "也许是归还力量后，瓦勒姆家会失去一切。\n"
                .. "也许更严重。也许是……\n\n"
                .. "你不敢往下想。\n\n"
                .. name .. "拿起那把水晶钥匙翻看了一下。\n"
                .. "「这把钥匙——」他皱了皱眉，像是想起了什么但又抓不住，\n"
                .. "「我好像在哪里见过……不，不是见过。是——」\n\n"
                .. "他捏着钥匙的手忽然开始发烫。他本能地松了手。\n"
