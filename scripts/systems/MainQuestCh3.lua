    if passageName == "主线3_父信分享" then
        return {
            text = "你把信递给" .. name .. "。\n\n"
                .. "他接过去，一个字一个字地读。\n\n"
                .. "读到「瓦勒姆家的力量是交易换来的」时，他的眉头皱了一下。\n"
