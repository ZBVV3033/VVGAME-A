    -- ==================== 阶段15：莱德的封印 ====================

    if passageName == "主线3_莱德封印" then
        S.mqStage = 15
        TimeSystem.addMinutes(30)

        return {
            text = "你来到教堂时，克丽丝正在修补砸碎的彩绘玻璃。\n\n"
                .. "看到你和" .. name .. "，她放下手里的碎片：\n"
                .. "「你来了——暴动之后教堂清理了地下室。那些符文都被抹掉了。\n"
