local GameState = require("systems.GameState")
local TimeSystem = require("systems.TimeSystem")
local NPCSystem = require("systems.NPCSystem")

local MainQuestCh3 = {}

--- 第三章段落路由
---@param passageName string
---@return table|nil
function MainQuestCh3.getPassage(passageName)
    local S = GameState.state
    local name = S.initialName or "莱德"

    -- ==================== 阶段13：暴动爆发 ====================

    if passageName == "主线3_暴动爆发" then
        S.mqStage = 13
        TimeSystem.addMinutes(30)

        local routeContext = ""
        local route = S.mq2Route or 0
        if route == 1 then
            routeContext = "黑帮少主说过的'信号'——今天它来了。你不知道少主是推动者还是旁观者。"
        elseif route == 2 then
            routeContext = "梅菲斯苦心经营的和谈还没开始，就被这场暴动烧成了灰烬。"
        elseif route == 3 then
            routeContext = "奥梅尔警告过你——有人在幕后操控。暴动正是那个幕后势力想要的。"
        end

        return {
            text = "你被一声巨响惊醒。\n\n"
                .. "窗外的天空是橘红色的。不是黎明——是火焰。\n\n"
                .. name .. "已经站在窗边了，脸上映着火光：「……开始了。」\n\n"
                .. "你冲到门口，整条街都在骚动。人们提着水桶往南边跑，"
                .. "喊声、哭声、玻璃碎裂声混在一起。\n\n"
                .. "一个浑身煤灰的男孩跑过来喘着气说：\n"
                .. "「商业区的粮铺被人砸了！贵族的仓库着火了！到处都在打——」\n\n"
                .. "K从酒馆二楼探出头，面具下的声音平静如常：\n"
                .. "「诺兰，你有两个选择。出去看看情况，或者留在这里等它结束。」\n\n"
                .. "她的语气告诉你——这不是一场简单的骚乱。\n\n"
                .. routeContext .. "\n\n"
                .. name .. "抓起桌上的匕首：「我跟你一起去。」\n"
                .. "他的表情没有犹豫——这种时候，他永远站在你身边。",
            choices = {
                { text = "「我们去商业区——那里的人最多。」", action = function()
                    NPCSystem.modStat("YG", 3)  -- 勇敢
                    return "主线3_暴动商业区"
                end },
                { text = "「先去教堂——修女和孩子们在那里。」", action = function()
                    NPCSystem.modStat("ML", 3)  -- 魅力/善良
                    return "主线3_暴动教堂"
                end },
                { text = "「去找黑帮少主——他能控制局面。」", action = function()
                    NPCSystem.modStat("LG", 3)
                    return "主线3_暴动花街"
                end },
            },
        }
    end

    if passageName == "主线3_暴动商业区" then
        TimeSystem.addMinutes(20)

        return {
            text = "你和" .. name .. "冲进商业区。广场上一片混乱。\n\n"
                .. "几个蒙面的人在砸一家药铺的窗户，老板抱着药箱在角落里瑟瑟发抖。\n"
                .. "更远处，有人推翻了一辆贵族马车，火苗舔着车厢。\n\n"
                .. "但你注意到一些奇怪的地方——\n"
                .. "砸店的人动作太整齐了。他们不是失控的暴民，更像是有组织的行动。\n"
                .. "而且，每砸完一家店，他们就在墙上画一个符号——\n\n"
                .. "残缺的太阳。中心被挖空的太阳。\n\n"
                .. "暗教会？！\n\n"
                .. name .. "一把拉住你：「别愣着——那边有人受伤了！」\n\n"
                .. "你们帮一个腿被砸伤的面包师傅挪到安全的地方。\n"
                .. "他喘着气说：「不是黑帮干的……那些人从地下冒出来的……\n"
                .. "穿黑袍……眼睛发紫光……」\n\n"
                .. "（勇气+3）",
            choices = {
                { text = "「暗教会在利用暴动掩护他们的行动！」", action = function()
                    S.mq3TruthLevel = (S.mq3TruthLevel or 0) + 1
                    return "主线3_暴动发现"
                end },
            },
        }
    end

    if passageName == "主线3_暴动教堂" then
        TimeSystem.addMinutes(20)

        return {
            text = "教堂的门被死死抵住了。你敲了半天，克丽丝修女才打开一条缝。\n\n"
                .. "「谢太阳神你来了——」她的脸上有血，手还在抖，\n"
                .. "「地下室里有二十多个孩子和老人。那些暴徒刚才试图闯进来——」\n\n"
                .. "你环顾教堂内部。彩绘玻璃被砸了几块，地上全是碎片。\n"
                .. "但大部分人安全。\n\n"
                .. name .. "已经开始帮忙搬桌子堵门了。他的动作熟练得像是做过很多次——\n"
                .. "也许在他失去记忆之前的岁月里，他确实做过。\n\n"
                .. "克丽丝把你拉到一边，压低声音：\n"
                .. "「不是普通暴动。那些砸门的人穿着黑袍，画残缺的太阳——\n"
                .. "和地下室那个修士一样的符号！」\n\n"
                .. "她的声音在发颤：「他们说要'取出太阳的核心'。诺兰——他们在找什么？」\n\n"
                .. "你想起了暗教会那张纸条的内容。瓦勒姆家的血脉。最后一把钥匙。\n\n"
                .. "（魅力+3）",
            choices = {
                { text = "「他们在找我。」", action = function()
                    S.mq3TruthLevel = (S.mq3TruthLevel or 0) + 1
                    return "主线3_暴动发现"
                end },
            },
        }
    end

    if passageName == "主线3_暴动花街" then
        TimeSystem.addMinutes(20)

        return {
            text = "花街的小巷里出奇地安静。\n\n"
                .. "你找到黑帮少主时，他正站在据点门口，嘴角叼着一根蛋糕卷——\n"
                .. "但他的眼神是你从未见过的凶狠。\n\n"
                .. "「不是我干的。」他在你开口之前就说了。\n\n"
                .. "「我知道你会来问。不是我下的命令。我的人已经全部收了回来。\n"
                .. "外面闹事的不是我们。」\n\n"
                .. "他的手下匆匆跑来报告：「少主，那些人……穿黑袍，眼睛发紫光。\n"
                .. "不像是我们这一行的。他们在每个砸过的地方画太阳——但太阳是残缺的。」\n\n"
                .. "黑帮少主的表情变了。他把蛋糕卷一口吞了：\n"
                .. "「残缺的太阳？那是暗教会的标记。\n"
                .. "我以为那些人只是传说……」\n\n"
                .. "他看着你：「你知道的比我多，对吧？」\n\n"
                .. "（洞察+3）",
            choices = {
                { text = "「暗教会在利用这场混乱。他们有更大的目的。」", action = function()
                    S.mq3TruthLevel = (S.mq3TruthLevel or 0) + 1
                    return "主线3_暴动发现"
                end },
            },
        }
    end

    if passageName == "主线3_暴动发现" then
        TimeSystem.addMinutes(10)

        return {
            text = "暴动持续了整整一天。傍晚时分，贵族的私兵终于赶到，"
                .. "把大部分暴徒驱散了。\n\n"
                .. "但黑袍人已经消失得无影无踪。\n\n"
                .. "你回到家，疲惫地坐在椅子上。" .. name .. "给你端了杯水，"
                .. "自己靠在墙角，衣服上沾满了灰尘和烟味。\n\n"
                .. "K站在桌边，少有地摘下了面具。她的精灵尖耳在烛光下微微颤动，"
                .. "光环比平时暗淡——像是今天消耗了什么力量。\n\n"
                .. "「暗教会的人在找'太阳核心'。」K轻声说，\n"
                .. "「而他们认为——钥匙在瓦勒姆家的血脉里。」\n\n"
                .. "她看着你。\n\n"
                .. "「也就是说，他们在找你。或者——你哥哥。」\n\n"
                .. name .. "猛地站起来：「什么意思？」\n\n"
                .. "K摇了摇头：「我不能说太多。神使有神使的规矩——\n"
                .. "太阳神交代的事务，不是我能随意透露的。\n"
                .. "但——如果你想知道真相，从你父亲留下的东西开始找。」\n\n"
                .. "她戴上面具，退回角落。\n\n"
                .. "你低头看着自己的手。瓦勒姆的血。太阳的钥匙。\n"
                .. "你的父亲到底做了什么？",
            choices = {
                { text = "「明天去翻找父亲的遗物。」", target = "家" },
                { text = "「K——你为什么帮我？」", action = function()
                    NPCSystem.addAffection("k", 5)
                    return "主线3_K的温柔"
                end },
            },
        }
    end

    if passageName == "主线3_K的温柔" then
        return {
            text = "K在门口停了一下。\n\n"
                .. "「为什么帮你？」她重复你的问题，像是在品味一杯酒。\n\n"
                .. "她转过身来。面具遮住了大部分表情，但你看得到她唇角的弧度——\n"
                .. "那是一种很温柔、很古老的微笑。\n\n"
                .. "「因为你是第一个——」她说，声音轻到像蝴蝶的翅膀，\n"
                .. "「第一个问我'为什么'而不是'能不能'的人。」\n\n"
                .. "她顿了顿：「别人来酒馆找我，都是求庇护、求帮忙、求解决麻烦。\n"
                .. "只有你——你问我今天过得好不好，问我面具戴着热不热，\n"
                .. "问我要不要也坐下来吃饭。」\n\n"
                .. "她的光环微微亮了一下。\n\n"
                .. "「神使不该对人类有私心。教会枢机更不该偏袒谁。但——」\n"
                .. "她摸了摸自己尖长的耳朵，像是在触碰一段遥远的、还没升天时的记忆，\n"
                .. "「也许精灵的那一半，可以。毕竟我不是生来就是天使。」\n\n"
                .. "她退回了角落，不再多说。\n\n"
                .. "（K 好感+5）",
            choices = {
                { text = "（她的话在你心里留下了柔软的印痕）", target = "家" },
            },
        }
    end

    -- ==================== 阶段14：父亲的交易 ====================

    if passageName == "主线3_父亲的交易" then
        S.mqStage = 14
        S.mq3FatherSecret = true
        TimeSystem.addMinutes(30)

        return {
            text = "你翻遍了衣柜的每一层。\n\n"
                .. "旧衣服、破毯子、落了灰的书本。你几乎要放弃了——\n"
                .. "直到你摸到衣柜底板有一处微微凸起。\n\n"
                .. "你用匕首撬开了暗格。\n\n"
                .. "里面是一个用蜡封住的皮匣子。蜡上印着瓦勒姆家的纹章——\n"
                .. "一轮完整的太阳。不是残缺的。\n\n"
                .. "你打开匣子。里面有三样东西：\n"
                .. "一封信、一枚金色的徽章、和一把小小的水晶钥匙。\n\n"
                .. name .. "凑过来。他看到徽章上的太阳图案，微微皱了皱眉。\n\n"
                .. "你展开信。字迹颤抖，有些地方被水渍模糊了——也许是泪痕。\n\n"
                .. "「致我的孩子诺兰：\n\n"
                .. "  如果你找到这封信，说明一切已经无法挽回。\n\n"
                .. "  我必须告诉你真相。瓦勒姆家的力量不是天赋——它是交易换来的。\n"
                .. "  二十年前，我用自己的理智作为代价，向太阳神借了力量。\n"
                .. "  但力量是有利息的。每一代瓦勒姆的长子，都必须继承这笔债务。\n\n"
                .. "  你的哥哥乌列尔……他已经在还了。他的冷漠不是天生的——\n"
                .. "  是债务在一点一点吞噬他的感情。\n\n"
                .. "  但有一种方法可以终结这一切。太阳神殿的深处有一个'核心'。\n"
                .. "  如果有人用瓦勒姆的血打开封印，把核心归还——\n"
                .. "  这笔债务就能清除。代价是……\n\n"
                .. "  我写不下去了。你会懂的。对不起，诺兰。对不起。\n\n"
                .. "                              ——你的父亲    」\n\n"
                .. "你的手在抖。信纸上的最后几个字已经被泪水洇开了——\n"
                .. "不是你的眼泪。是你父亲写信时留下的。",
            choices = {
                { text = "「……乌列尔在还债？他的冷漠不是天生的？」", action = function()
                    S.mq3TruthLevel = (S.mq3TruthLevel or 0) + 1
                    return "主线3_父信震惊"
                end },
                { text = "把信给" .. name .. "看", action = function()
                    NPCSystem.addAffection("initialName", 5)
                    S.mq3TruthLevel = (S.mq3TruthLevel or 0) + 1
                    return "主线3_父信分享"
                end },
                { text = "「代价是什么？他没写完……」", action = function()
                    S.mq3TruthLevel = (S.mq3TruthLevel or 0) + 1
                    return "主线3_父信追问"
                end },
            },
        }
    end

    if passageName == "主线3_父信震惊" then
        return {
            text = "你把信念了一遍又一遍。\n\n"
                .. "乌列尔的冷漠。他用三个字就能表达的惜字如金。\n"
                .. "他从不对弟弟以外的人表达任何情感。\n\n"
                .. "你一直以为那是他的性格。\n\n"
                .. "但如果——如果那不是性格，而是代价呢？\n"
                .. "如果他的感情正在一点一点被吞噬，而他对你的温柔——\n"
                .. "是他拼命保留的最后一点东西呢？\n\n"
                .. name .. "在你身边安静地坐着。他不说话，只是陪着你。\n\n"
                .. "过了很久，你把那枚金色徽章挂在脖子上，把水晶钥匙放进口袋。\n\n"
                .. "「我需要去教堂。」你说。\n"
                .. "信上说太阳神殿——而教堂是离太阳神最近的地方。\n"
