                .. "他的手抬起来，像是想拍你的头——但停在半空中，又放下了。\n"
                .. "身体敏感但精神冷淡的他，大概只能做到这个程度了。\n\n"
                .. "（" .. name .. " 好感+5）\n"
                .. "（真相揭露程度+1）",
            choices = {
                { text = "（你看到他的手停了，心里有什么东西涌了上来）", target = "十字路口" },
