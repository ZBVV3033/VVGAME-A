local GameState = require("systems.GameState")
local TimeSystem = require("systems.TimeSystem")
local NPCSystem = require("systems.NPCSystem")

local MainQuestCh2 = {}

--- 第二章段落路由
---@param passageName string
---@return table|nil
function MainQuestCh2.getPassage(passageName)
    local S = GameState.state
    local name = S.initialName or "莱德"

    -- ==================== 阶段6：阶级矛盾浮现 ====================

    if passageName == "主线2_阶级矛盾" then
        S.mqStage = 6
        TimeSystem.addMinutes(20)

        return {
            text = "十字路口的人群忽然往一边涌动，你被裹挟着挤到了最前面。\n\n"
                .. "一辆华丽的马车横在路中央，车夫挥着鞭子驱赶行人。一个挑着扁担的老人被马车撞倒，"
                .. "篮子里的水果散落一地。\n\n"
                .. "「滚开！挡了罗斯巴特老爷的路！」车夫厉声喝道。\n\n"
                .. "老人艰难地爬起来，一声不吭地捡拾水果。没有人上前帮忙——人们只是低下头，"
                .. "默默地让出更宽的路。\n\n"
                .. "马车帘子掀开，一个衣着华贵的中年男人探出头，不耐烦地看了一眼："
                .. "「让他快点，我赶时间。」\n\n"
                .. "你注意到人群中有人攥紧了拳头，有人低声咒骂，但没有人站出来。\n"
                .. "空气中弥漫着一股压抑的怒火，像暴风雨前的闷热。",
            choices = {
                { text = "上前帮老人捡水果", action = function()
                    NPCSystem.modStat("YG", 2)  -- 勇气
                    return "主线2_帮助老人"
                end },
                { text = "大声斥责车夫", action = function()
                    NPCSystem.modStat("YG", 3)
                    S.mq2ConfrontNoble = true
                    return "主线2_斥责车夫"
                end },
                { text = "默默观察人群的反应", action = function()
                    NPCSystem.modStat("LG", 2)  -- 灵感/洞察
                    return "主线2_观察人群"
                end },
            },
        }
    end

    if passageName == "主线2_帮助老人" then
        return {
            text = "你挤过人群，蹲下来帮老人捡散落的水果。\n\n"
                .. "「谢谢你，小伙子……」老人的手在抖，声音很轻，「别为我惹麻烦。」\n\n"
                .. "车夫不屑地哼了一声，甩了个响鞭。马车辘辘驶过，溅起的泥水弄脏了你的衣角。\n\n"
                .. "人群渐渐散去。一个戴帽子的年轻人在你身边停了一下：\n"
                .. "「你做了对的事。」他压低声音，「但对的事在这座城里不值钱。」\n\n"
                .. "他塞给你一张折了角的传单就走了。你展开一看——上面写着：\n"
                .. "「日轮王国不需要两个太阳。平民不是脚下的泥。」\n\n"
                .. "传单的角落印着一个拳头的标记。\n\n"
                .. "你把传单收进口袋。老人已经走远了，他的背影在午后的阳光下显得格外佝偻。\n"
                .. "你心里有一种说不清的闷堵感。",
            choices = {
                { text = "回家", action = function()
                    TimeSystem.addMinutes(5)
                    return "家"
                end },
            },
        }
    end

    if passageName == "主线2_斥责车夫" then
        return {
            text = "「够了！」你挤上前，声音比自己预想的大，「老人倒了你看不见吗？」\n\n"
                .. "车夫愣了一下，随即恼羞成怒：「你谁啊？这是罗斯巴特家的车——」\n\n"
                .. "马车里传来一声冷哼，帘子被掀开。那个贵族扫了你一眼，"
                .. "像在审视一只趴在路中间的虫子：「一个自由冒险者？」\n\n"
                .. "他没理你，只对车夫说：「走。别跟野狗计较。」\n\n"
                .. "马车驶走了。人群中有人向你投来赞赏的目光，也有人摇头叹气。\n\n"
                .. "一个穿着旧皮衣的年轻人走过来拍了拍你的肩膀：\n"
                .. "「有种。」他的语气意味深长，「如果你想做更多——来花街找我。问'甜点少爷'在哪就行。」\n\n"
                .. "他转身消失在人群中。你隐约猜到，这个人和黑帮有关。\n\n"
                .. "（勇气+3）",
            choices = {
                { text = "回家", action = function()
                    TimeSystem.addMinutes(5)
                    return "家"
                end },
            },
        }
    end

    if passageName == "主线2_观察人群" then
        return {
            text = "你退到人群后面，仔细观察。\n\n"
                .. "大多数人低着头回避，但你注意到几个不一样的人——\n\n"
                .. "一个戴帽子的年轻人在默默记录着什么，像是在写日记。\n"
                .. "一个穿旧皮衣的人靠在墙上，嘴角挂着冷笑。\n"
                .. "教堂门口的克丽丝修女紧紧握着十字架，嘴唇微微颤动，像是在祈祷。\n\n"
                .. "你还看到了更微妙的东西——贵族马车驶过时，好几个人同时把手伸进了口袋。"
                .. "你不确定他们在握什么，但那种整齐划一的动作，不像是巧合。\n\n"
                .. "这座看起来和平的小镇，表面下暗流涌动。阶级之间的裂痕比你想象的深得多。\n\n"
                .. "（洞察+2）",
            choices = {
                { text = "回家", action = function()
                    TimeSystem.addMinutes(5)
                    return "家"
                end },
            },
        }
    end

    -- ==================== 阶段7：外套回忆（核心场景） ====================

    if passageName == "主线2_外套回忆" then
        TimeSystem.addMinutes(30)

        return {
            text = "你推开家门，看见" .. name .. "坐在桌边。\n\n"
                .. "他手里拿着一件旧外套。那件外套你见过——他到这里的时候就穿着，"
                .. "破旧得不像话，袖口已经磨得起毛，扣子只剩两颗。\n\n"
                .. "「你在看什么？」你在对面坐下。\n\n"
                .. name .. "没有立刻回答。过了好一会儿，他才开口，声音很轻：\n"
                .. "「你还记不记得……我们第一次见面？」\n\n"
                .. "你心里一震。\n\n"
                .. "当然记得。那年你八岁，在山洞里发现一个沉睡的人。比你高，比你大，比你像大人。\n"
                .. "你拿走了他身上的外套——那时候你只觉得好玩——\n"
                .. "跑出去扔在草地上，用脚踩着玩。\n\n"
                .. "你不知道那是什么。不知道那个人是谁。\n"
                .. "不知道你拿走的那件外套，是他醒来之后唯一的东西。\n\n"
                .. name .. "抬起头看着你。他的表情很平静，但你看得出来，他的指尖在微微发抖。\n\n"
                .. "「后来我醒了。」他说，「什么都没有。衣服没了，东西没了。"
                .. "我光着脚走了三天，靠打架活下来的。」\n\n"
                .. "他没有责怪你的意思。他只是在陈述事实。\n\n"
                .. "但你心里像被什么东西狠狠揪住了。",
            choices = {
                { text = "「……对不起。」", action = function()
                    S.mq2CoatChoice = 1
                    NPCSystem.addAffection("initialName", 15)
                    return "主线2_外套告白"
                end },
                { text = "移开视线，不知道该说什么", action = function()
                    S.mq2CoatChoice = 2
                    NPCSystem.addAffection("initialName", 5)
                    return "主线2_外套回避"
                end },
                { text = "「那件外套……你为什么还留着？」", action = function()
                    S.mq2CoatChoice = 3
                    NPCSystem.addAffection("initialName", 10)
                    return "主线2_外套反问"
                end },
            },
        }
    end

    if passageName == "主线2_外套告白" then
        S.mqStage = 7

        return {
            text = "「对不起。」\n\n"
                .. "你说出口的时候，声音比你想象的小。\n\n"
                .. name .. "看着你，那双没什么表情的眼睛里，有什么东西在微微波动。\n\n"
                .. "「我那时候……什么都不懂。」你低下头，"
                .. "「我不知道那是你唯一的东西。我——」\n\n"
                .. "「别说了。」\n\n"
                .. name .. "打断了你。他把外套叠好，放在桌上。\n\n"
                .. "「我没有怪你。」他说，「八岁的小鬼知道什么？」\n\n"
                .. "他的语气很淡，但他的手指在外套上停留了很久。\n\n"
                .. "「而且——」他顿了顿，像是在斟酌措辞，「你后来把我从小奥那里救出来了。」\n\n"
                .. "他站起来，走到窗边。夕阳照在他脸上，你第一次注意到他睫毛很长。\n\n"
                .. "「扯平了。」他背对着你说。\n\n"
                .. "你知道没有扯平。但你也知道，这句话是他能说出口的最温柔的话了。\n\n"
                .. "（" .. name .. " 好感+15）\n"
                .. "（你的心里，有什么东西变得不一样了。）",
            choices = {
                { text = "（默默把这一刻记在心里）", target = "十字路口" },
            },
        }
    end

    if passageName == "主线2_外套回避" then
        S.mqStage = 7

        return {
            text = "你移开了视线。\n\n"
                .. "你不知道该说什么。道歉？太轻了。解释？没什么好解释的。\n\n"
                .. "沉默在两个人之间蔓延。窗外的夕阳把影子拉得很长。\n\n"
                .. name .. "把外套叠好，站了起来。\n\n"
                .. "「没什么。」他说，「只是忽然想起来了。」\n\n"
                .. "他走向自己的房间，在门口停了一下：\n"
                .. "「明天的晚饭，我来做。」\n\n"
                .. "门关上了。\n\n"
                .. "你坐在桌边，看着那件叠好的外套。\n"
                .. "有些话没有说出口，就变成了心里的一道褶皱。也许哪天会被熨平，也许不会。\n\n"
                .. "（" .. name .. " 好感+5）",
            choices = {
                { text = "（这个夜晚格外安静）", target = "十字路口" },
            },
        }
    end

    if passageName == "主线2_外套反问" then
        S.mqStage = 7

        return {
            text = "「那件外套……你为什么还留着？」\n\n"
                .. name .. "低头看了看手里的外套。他沉默了很久。\n\n"
                .. "「不知道。」他说。然后又补了一句：「可能是……习惯了。」\n\n"
                .. "你觉得不止是习惯。\n\n"
                .. "「这是你来到这个世界后的第一件东西。」你试探着说。\n\n"
                .. name .. "抬起头。他的表情依然平静，但眼底有一瞬间的惊讶——\n"
                .. "像是没想到你会这么理解他。\n\n"
                .. "「……差不多吧。」他把外套往你面前推了推，「你拿走了它，又救了我。"
                .. "拿走东西的人和给我东西的人是同一个。」\n\n"
                .. "他的声音放得很低：\n\n"
                .. "「挺荒唐的，对吧。」\n\n"
                .. "你伸手碰了碰那件外套的布料。磨得起毛的袖口，缺了的扣子。\n"
                .. "六年的时光凝结在这些痕迹里。\n\n"
                .. "（" .. name .. " 好感+10）\n"
                .. "（你们之间的某些东西，正在悄悄改变。）",
            choices = {
                { text = "（你觉得自己欠他的，远不止一件外套）", target = "十字路口" },
            },
        }
    end

    -- ==================== 阶段8：三路分歧 ====================

    if passageName == "主线2_三路分歧" then
        TimeSystem.addMinutes(15)

        return {
            text = "今天的十字路口格外热闹——但不是那种好的热闹。\n\n"
                .. "三拨不同的人几乎同时出现在你面前。\n\n"
                .. "一个穿旧皮衣的年轻人靠在喷泉边，冲你抬了抬下巴。你认出他——那天阶级冲突时见过。\n"
                .. "他代表的是黑帮少主的势力，底层民众的愤怒。\n\n"
                .. "梅菲斯从教堂方向走来，步伐从容。他微微颔首：「小诺兰，有空聊聊吗？我觉得"
                .. "现在需要一个能在两边说话的人。」他的态度温和而中立。\n\n"
                .. "第三个人你不认识——一个穿着得体的年轻仆从，他拿出一封信：\n"
                .. "「罗斯巴特少爷奥梅尔请您明日下午到他的宅邸一叙。他说……」"
                .. "仆从犹豫了一下，「他说有些事想当面跟您谈清楚。」\n\n"
                .. "三条路。三种立场。三种不同的未来。\n\n"
                .. "你不可能同时满足所有人。",
            choices = {
                { text = "「带我去见那位'甜点少爷'。」（黑帮路线）", action = function()
                    S.mq2Route = 1
                    S.mqStage = 8
                    return "主线2_黑帮路线开始"
                end },
                { text = "「梅菲斯先生，你的提议很有意思。」（调停路线）", action = function()
                    S.mq2Route = 2
                    S.mqStage = 8
                    return "主线2_调停路线开始"
                end },
                { text = "「告诉奥梅尔，我会去的。」（贵族路线）", action = function()
                    S.mq2Route = 3
                    S.mqStage = 8
                    return "主线2_贵族路线开始"
                end },
            },
        }
    end

    -- ==================== 黑帮路线 ====================

    if passageName == "主线2_黑帮路线开始" then
        TimeSystem.addMinutes(30)

        return {
            text = "旧皮衣年轻人带你穿过花街的小巷，七拐八弯，来到一扇不起眼的门前。\n\n"
                .. "「进去。」他推开门。\n\n"
                .. "里面出乎意料地整洁。几张木桌，几盏油灯，角落里摆着一个精致的蛋糕架——"
                .. "上面居然摆着三层小蛋糕。\n\n"
                .. "一个年轻人坐在最里面，正用叉子小心翼翼地吃一块草莓蛋糕。\n"
                .. "看见你，他擦了擦嘴角，站了起来。\n\n"
                .. "「你就是在街上怼贵族马车的那个？」他打量着你，嘴角带笑，"
                .. "「有意思。我是这一带的……管事的。叫我少主就行。」\n\n"
                .. "他把蛋糕推到你面前：「吃。别跟我客气。」\n\n"
                .. "黑帮少主没有你想象中的凶狠。他的眼睛很亮，笑起来甚至有点孩子气。\n"
                .. "但你注意到他的手上有旧伤疤，指关节处的茧很厚——这不是只吃甜食的手。\n\n"
                .. "「最近贵族越来越过分了。」他收起笑容，「税提了三次，商铺被强制搬迁，"
                .. "不听话的直接派人砸店。底下的人已经忍不住了。」\n\n"
                .. "他看着你：「你不是贵族，也不是我们的人。刚好——我需要一个外面的声音。"
                .. "帮我做几件事，我帮你在这座城里站稳脚跟。怎么样？」",
            choices = {
                { text = "「具体要做什么？」", action = function()
                    S.mqStage = 9
                    S.mq2RouteProgress = 0
                    S.mq2GangTrust = (S.mq2GangTrust or 0) + 2
                    return "主线2_黑帮任务说明"
                end },
                { text = "「我不想卷入暴力。」", action = function()
                    S.mqStage = 9
                    S.mq2RouteProgress = 0
                    S.mq2GangTrust = (S.mq2GangTrust or 0) + 1
                    return "主线2_黑帮温和立场"
                end },
            },
        }
    end

    if passageName == "主线2_黑帮任务说明" then
        return {
            text = "黑帮少主扳着手指头数：\n\n"
                .. "「第一，帮我打听罗斯巴特家最近的动向——他们在筹备什么大事，但消息封得很死。\n"
                .. "第二，有几个被贵族欺负的商户，帮我去安抚一下，让他们别急着闹事。\n"
                .. "第三……」他犹豫了一下，「帮我带个话给教堂的人。具体什么话，到时候告诉你。」\n\n"
                .. "他吃了一口蛋糕：「不需要你打架。我这边不缺会打架的。\n"
                .. "缺的是能在不同地方走动、不引起怀疑的人。」\n\n"
                .. "他抬起头，认真地看着你：\n"
                .. "「做完这三件事，你就是我的朋友。我的朋友在这座城里不会饿肚子。」\n\n"
                .. "（黑帮信任+2）\n"
                .. "（接下来在花街、商业区、教堂行动时会触发黑帮路线任务）",
            choices = {
                { text = "「成交。」", target = "花街" },
            },
        }
    end

    if passageName == "主线2_黑帮温和立场" then
        return {
            text = "黑帮少主挑了挑眉，没有生气。\n\n"
                .. "「暴力？」他笑了，「我不需要你打架。我有的是打架的人。」\n\n"
                .. "他放下叉子，收起了笑容：「我需要的是情报、跑腿、传话。"
                .. "你在街上走来走去，没人会怀疑一个自由冒险者。」\n\n"
                .. "他站起来走到你面前，拍了拍你的肩膀：\n"
                .. "「想想。在这座城里，平民连人行道都要给贵族让路。"
                .. "你觉得这样对吗？」\n\n"
                .. "他的问题很简单，但你知道答案并不简单。\n\n"
                .. "（黑帮信任+1）\n"
                .. "（接下来在花街、商业区、教堂行动时会触发黑帮路线任务）",
            choices = {
                { text = "（离开，需要时间想想）", target = "花街" },
            },
        }
    end

    -- ==================== 调停路线 ====================

    if passageName == "主线2_调停路线开始" then
        TimeSystem.addMinutes(30)

        return {
            text = "梅菲斯带你来到教堂的侧厅。这里很安静，只有壁炉的火在噼啪作响。\n\n"
                .. "他给你倒了一杯茶，自己坐在对面：\n\n"
                .. "「我在这座城生活了很久。」他说，声音温和但不失严肃，\n"
                .. "「我见过贵族的傲慢，也见过黑帮的暴戾。两边都有道理，两边都有问题。」\n\n"
                .. "他看着你：「你是自由冒险者，不属于任何一方。这是你的优势，也是你的危险。\n"
                .. "如果你愿意——我需要一个信使。一个能让双方都坐下来谈的人。」\n\n"
                .. "你问他为什么要做这件事。\n\n"
